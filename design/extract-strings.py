# Regenerate arabic-strings.js from the Kotlin sources.
#
#   python design\extract-strings.py
#
# Python rather than PowerShell on purpose: Get-Content/Set-Content round-trips
# mangle the Arabic (and the U+200E marks the detectors depend on) into mojibake.
#
# Two things this must get right:
#   - anything under detect/ is LOCKED. Those are not our words; they are the
#     words AutoFare searches for inside Jeeny and Petra's own screens, and
#     rewording them breaks detection silently.
#   - Log lines are not copy. They are skipped so the review page is 250 strings
#     a driver could read, not 300 with debug noise in the middle.

import io
import json
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "android", "app", "src", "main", "java", "jo", "autofare")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "arabic-strings.js")

ARABIC = re.compile(r"[؀-ۿ]")

# Kotlin double-quoted literal, honouring backslash escapes. Triple-quoted raw
# strings are skipped — none of the copy uses them and the naive match would
# swallow whole files.
LITERAL = re.compile(r'"((?:[^"\\\n]|\\.)*)"')

# Lines that are plumbing rather than copy.
SKIP_LINE = re.compile(r"android\.util\.Log|Log\.[iwde]\(|\bTAG\b|contentDescription|onClickLabel")

# Comment lines. KDoc in this project quotes the Arabic it is describing, which
# would otherwise show up in the review as a string the driver can edit.
COMMENT = re.compile(r"^\s*(//|\*|/\*)")

# Longest prefix wins, so detect/ cannot be shadowed by a looser rule.
SCREENS = [
    (os.path.join("ui", "home"),       "الرئيسية"),
    (os.path.join("ui", "rules"),      "قواعد القبول"),
    (os.path.join("ui", "stats"),      "الإحصائيات"),
    (os.path.join("ui", "settings"),   "الإعدادات"),
    (os.path.join("ui", "learn"),      "وضع التعلّم"),
    (os.path.join("ui", "onboard"),    "التشغيل الأول"),
    (os.path.join("ui", "splash"),     "البداية"),
    (os.path.join("ui", "components"), "مكوّنات مشتركة"),
    (os.path.join("ui", "theme"),      "الثيم"),
    ("ui",                             "الشريط السفلي"),
    ("rules",                          "أسباب الرفض"),
    (os.path.join("data", "RideApp"),  "أسماء التطبيقات"),
    ("data",                           "التخزين"),
    (os.path.join("service", "LearnNotifier"), "إشعارات"),
    ("service",                        "الخدمة"),
    ("auto",                           "القبول التلقائي"),
    ("detect",                         "كلمات التعرّف — ما بتتغيّر"),
]


def screen_for(rel):
    best, label = -1, "غير مصنّف"
    for prefix, name in SCREENS:
        if rel.startswith(prefix) and len(prefix) > best:
            best, label = len(prefix), name
    return label


def main():
    rows = []
    for folder, _, files in os.walk(SRC):
        for name in sorted(files):
            if not name.endswith(".kt"):
                continue

            full = os.path.join(folder, name)
            rel = os.path.relpath(full, SRC)
            # detect/ holds the words we search for inside other apps
            locked = rel.split(os.sep)[0] == "detect"
            screen = screen_for(rel)

            with io.open(full, encoding="utf-8") as f:
                for lineno, line in enumerate(f, start=1):
                    if COMMENT.match(line) or SKIP_LINE.search(line):
                        continue
                    for m in LITERAL.finditer(line):
                        text = m.group(1)
                        if not ARABIC.search(text):
                            continue
                        rows.append({
                            "id": "%s:%d:%d" % (rel, lineno, m.start()),
                            "file": rel,
                            "line": lineno,
                            "screen": screen,
                            "locked": locked,
                            "text": text,
                        })

    # group by screen so the review page's section headers come out contiguous,
    # keeping source order inside each screen
    order = {name: i for i, (_, name) in enumerate(SCREENS)}
    rows.sort(key=lambda r: (order.get(r["screen"], 99), r["file"], r["line"]))

    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by design/extract-strings.py. Do not edit by hand.\n")
        f.write("const STRINGS = ")
        json.dump(rows, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")

    locked_n = sum(1 for r in rows if r["locked"])
    print("%d strings (%d locked) -> %s" % (len(rows), locked_n, OUT))
    for _, name in SCREENS:
        n = sum(1 for r in rows if r["screen"] == name)
        if n:
            print("   %-32s %d" % (name, n))


if __name__ == "__main__":
    main()
